import { formatDateTime } from '../lib/format'

const ACTION_LABELS = {
  REQUEST_SUBMITTED: 'Submitted the request',
  HEAD_APPROVED: 'Approved for the department',
  ASSET_VERIFIED_BY_AMA_POOL: 'Verified the assets',
  FINAL_AUTHORIZATION_BY_AMA_POOL: 'Authorized the movement',
  AMA_POOL_VERIFIED_AND_AUTHORIZED: 'Verified and authorized',
  REQUEST_REJECTED: 'Rejected the request',
  OFFICER_ASSIGNED: 'Scheduled the move',
  IT_OFFICER_ASSIGNED: 'Scheduled the IT move',
  TRANSPORT_STARTED_BY_POOL: 'Picked up the assets',
  IT_EQUIPMENT_PICKUP_STARTED: 'Picked up the equipment',
  RELOCATION_COMPLETED_BY_TRANSPORT_POOL: 'Delivered the assets',
  IT_RELOCATION_COMPLETED: 'Delivered and installed the equipment',
  REGISTER_UPDATED_AND_CLOSED_BY_AMA_POOL: 'Updated the register and closed the file'
}

export const actionLabel = (a) =>
  ACTION_LABELS[a] || (a || 'Updated').toLowerCase().replace(/_/g, ' ').replace(/^\w/, (c) => c.toUpperCase())

/** The recorded audit entries for a request. Nothing here is generated by the app. */
export default function ActivityLog({ entries = [] }) {
  if (!entries.length) {
    return <p className="text-sm text-slate-500">No activity has been recorded.</p>
  }
  return (
    <ol className="relative space-y-5 border-l border-slate-200 pl-5">
      {entries.map((e) => (
        <li key={e.id} className="relative">
          <span className={`absolute -left-[25px] top-1.5 h-2.5 w-2.5 rounded-full ring-4 ring-white ${e.action === 'REQUEST_REJECTED' ? 'bg-red-500' : 'bg-blue-500'}`} aria-hidden="true" />
          <p className="text-sm text-slate-900">
            <span className="font-medium">{e.performed_by_name}</span>{' '}
            <span className="text-slate-600">{actionLabel(e.action).replace(/^\w/, (c) => c.toLowerCase())}</span>
          </p>
          <p className="text-xs text-slate-400">{formatDateTime(e.created_at)}</p>
          {e.remarks && <p className="mt-1 rounded-lg bg-slate-50 px-3 py-2 text-sm text-slate-600">{e.remarks}</p>}
        </li>
      ))}
    </ol>
  )
}
