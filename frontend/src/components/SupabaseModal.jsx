import { useState, useEffect } from 'react'
import { Database, CheckCircle2, XCircle, Copy, Check, ExternalLink, X, RefreshCw, Key, Globe, Shield } from 'lucide-react'
import { getStoredSupabaseConfig, saveSupabaseConfig, isSupabaseConfigured, getSupabase } from '../lib/supabase'

export default function SupabaseModal({ isOpen, onClose }) {
  const [url, setUrl] = useState('')
  const [anonKey, setAnonKey] = useState('')
  const [testing, setTesting] = useState(false)
  const [testResult, setTestResult] = useState(null)
  const [copied, setCopied] = useState(false)
  const [activeTab, setActiveTab] = useState('settings') // 'settings' | 'sql'

  useEffect(() => {
    if (isOpen) {
      const config = getStoredSupabaseConfig()
      setUrl(config.url || '')
      setAnonKey(config.anonKey || '')
      setTestResult(null)
    }
  }, [isOpen])

  if (!isOpen) return null

  const isConfigured = isSupabaseConfigured()

  const handleTestAndSave = async (e) => {
    e.preventDefault()
    setTesting(true)
    setTestResult(null)

    try {
      if (!url.trim() || !anonKey.trim()) {
        throw new Error('Please enter both Supabase Project URL and Anon Key')
      }

      saveSupabaseConfig(url, anonKey)
      const client = getSupabase()
      if (!client) throw new Error('Could not initialize Supabase client with given credentials')

      // Probe Supabase by querying public.users or health check
      const { data, error } = await client.from('users').select('id, name').limit(1)
      if (error && error.code !== 'PGRST116') {
        // Even if table doesn't exist yet, we can check if it reached Supabase
        if (error.message.includes('relation "public.users" does not exist')) {
          setTestResult({
            success: true,
            warning: 'Connected to Supabase! Please run the SQL schema script in Supabase SQL editor to create the tables.',
            timestamp: new Date().toLocaleTimeString()
          })
          return
        }
        throw error
      }

      setTestResult({
        success: true,
        message: 'Successfully connected to Supabase backend! Live cloud database is active.',
        timestamp: new Date().toLocaleTimeString()
      })
    } catch (err) {
      setTestResult({
        success: false,
        error: err.message || 'Connection failed. Please check the URL and Anon Key.'
      })
    } finally {
      setTesting(false)
    }
  }

  const handleDisconnect = () => {
    saveSupabaseConfig('', '')
    setUrl('')
    setAnonKey('')
    setTestResult({
      success: true,
      message: 'Supabase disconnected. Using local backend fallback.'
    })
  }

  const handleCopySQL = () => {
    const sqlText = `-- Fixed Asset Movement Service - Supabase Tables
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT UNIQUE NOT NULL,
  role TEXT NOT NULL DEFAULT 'requesting_officer',
  department TEXT,
  staff_id TEXT,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.movement_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference_no TEXT UNIQUE NOT NULL,
  requesting_officer_id BIGINT,
  requesting_officer_staff_id TEXT,
  present_location TEXT NOT NULL,
  new_location TEXT NOT NULL,
  purpose TEXT NOT NULL,
  officer_doing_movement TEXT,
  officer_doing_movement_staff_id TEXT,
  authorized_by TEXT,
  authorized_by_staff_id TEXT,
  department TEXT,
  unit TEXT,
  movement_date DATE NOT NULL DEFAULT CURRENT_DATE,
  priority TEXT NOT NULL DEFAULT 'Normal',
  signature_requester TEXT,
  status TEXT NOT NULL DEFAULT 'pending_head',
  head_approved_by BIGINT,
  head_approved_at TIMESTAMPTZ,
  head_remarks TEXT,
  head_signature TEXT,
  ama_officer_approved_by BIGINT,
  ama_officer_approved_at TIMESTAMPTZ,
  ama_officer_remarks TEXT,
  ama_head_approved_by BIGINT,
  ama_head_name TEXT,
  ama_head_signature TEXT,
  ama_head_approved_at TIMESTAMPTZ,
  ama_head_remarks TEXT,
  ama_closed_by BIGINT,
  ama_closed_name TEXT,
  ama_closed_at TIMESTAMPTZ,
  ama_closing_remarks TEXT,
  rejection_remarks TEXT,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.movement_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  movement_request_id BIGINT REFERENCES public.movement_requests(id) ON DELETE CASCADE NOT NULL,
  item_no INT NOT NULL DEFAULT 1,
  name_of_asset TEXT NOT NULL,
  asset_code TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.transport_tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  movement_request_id BIGINT REFERENCES public.movement_requests(id) ON DELETE CASCADE NOT NULL,
  assigned_officer_id BIGINT,
  assigned_officer_name TEXT,
  vehicle_details TEXT,
  driver_type TEXT DEFAULT 'internal',
  driver_name TEXT,
  vendor_name TEXT,
  scheduled_date DATE,
  assessment_notes TEXT,
  assignment_notes TEXT,
  status TEXT NOT NULL DEFAULT 'pending_assignment',
  completed_at TIMESTAMPTZ,
  completion_notes TEXT,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Upgrade script for existing tables (safe to run multiple times)
ALTER TABLE public.transport_tasks ADD COLUMN IF NOT EXISTS assigned_officer_name TEXT;
ALTER TABLE public.transport_tasks ADD COLUMN IF NOT EXISTS driver_type TEXT DEFAULT 'internal';
ALTER TABLE public.transport_tasks ADD COLUMN IF NOT EXISTS driver_name TEXT;
ALTER TABLE public.transport_tasks ADD COLUMN IF NOT EXISTS vendor_name TEXT;
ALTER TABLE public.transport_tasks ADD COLUMN IF NOT EXISTS transport_started_by BIGINT;
ALTER TABLE public.transport_tasks ADD COLUMN IF NOT EXISTS transport_started_name TEXT;
ALTER TABLE public.transport_tasks ADD COLUMN IF NOT EXISTS transport_completed_by BIGINT;
ALTER TABLE public.transport_tasks ADD COLUMN IF NOT EXISTS transport_completed_name TEXT;
ALTER TABLE public.movement_requests ADD COLUMN IF NOT EXISTS head_approved_name TEXT;
ALTER TABLE public.movement_requests ADD COLUMN IF NOT EXISTS ama_officer_name TEXT;
ALTER TABLE public.movement_requests ADD COLUMN IF NOT EXISTS ama_officer_signature TEXT;
ALTER TABLE public.movement_requests ADD COLUMN IF NOT EXISTS ama_head_name TEXT;
ALTER TABLE public.movement_requests ADD COLUMN IF NOT EXISTS ama_closed_name TEXT;
ALTER TABLE public.audit_log ADD COLUMN IF NOT EXISTS performed_by_name TEXT;
ALTER TABLE public.audit_log ADD COLUMN IF NOT EXISTS transport_task_id BIGINT;

CREATE TABLE IF NOT EXISTS public.audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  movement_request_id BIGINT REFERENCES public.movement_requests(id) ON DELETE CASCADE,
  action TEXT NOT NULL,
  performed_by BIGINT,
  performed_by_name TEXT,
  remarks TEXT,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.drafts (
  user_id TEXT PRIMARY KEY,
  form JSONB NOT NULL DEFAULT '{}'::jsonb,
  items JSONB NOT NULL DEFAULT '[]'::jsonb,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Permissive RLS
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.movement_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.movement_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transport_tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.drafts ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow all users" ON public.users FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all requests" ON public.movement_requests FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all items" ON public.movement_items FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all transport" ON public.transport_tasks FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all audit" ON public.audit_log FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all drafts" ON public.drafts FOR ALL USING (true) WITH CHECK (true);`

    navigator.clipboard.writeText(sqlText)
    setCopied(true)
    setTimeout(() => setCopied(false), 2500)
  }

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-blue-950/40 backdrop-blur-xs font-sans">
      <div className="bg-white rounded-2xl border border-blue-200 shadow-xl max-w-xl w-full max-h-[90vh] flex flex-col overflow-hidden">
        {/* Modal Header */}
        <div className="flex items-center justify-between p-5 border-b border-blue-100 bg-gradient-to-r from-blue-50/50 to-white">
          <div className="flex items-center gap-3">
            <div className="w-9 h-9 rounded-xl bg-emerald-500 text-white flex items-center justify-center shadow-sm">
              <Database className="w-5 h-5" />
            </div>
            <div>
              <h2 className="text-sm font-bold text-slate-900 tracking-tight flex items-center gap-2">
                <span>Supabase Backend Integration</span>
                {isConfigured ? (
                  <span className="text-[10px] font-semibold text-emerald-700 bg-emerald-50 px-2 py-0.5 rounded-full border border-emerald-200">
                    Connected
                  </span>
                ) : (
                  <span className="text-[10px] font-semibold text-slate-500 bg-slate-100 px-2 py-0.5 rounded-full border border-slate-200">
                    Not Configured
                  </span>
                )}
              </h2>
              <p className="text-[11px] text-slate-500 mt-0.5">
                Connect your cloud Supabase project for real-time database persistence
              </p>
            </div>
          </div>

          <button onClick={onClose} className="p-1.5 text-slate-400 hover:text-slate-600 rounded-lg hover:bg-slate-100 transition">
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Tab Switcher */}
        <div className="flex items-center border-b border-blue-100 bg-blue-50/30 px-5 gap-4">
          <button
            onClick={() => setActiveTab('settings')}
            className={`py-3 text-xs font-semibold border-b-2 transition ${
              activeTab === 'settings'
                ? 'border-blue-600 text-blue-900'
                : 'border-transparent text-slate-500 hover:text-slate-900'
            }`}
          >
            Connection Settings
          </button>
          <button
            onClick={() => setActiveTab('sql')}
            className={`py-3 text-xs font-semibold border-b-2 transition ${
              activeTab === 'sql'
                ? 'border-blue-600 text-blue-900'
                : 'border-transparent text-slate-500 hover:text-slate-900'
            }`}
          >
            Supabase SQL Setup Script
          </button>
        </div>

        {/* Modal Body */}
        <div className="p-5 overflow-y-auto space-y-4 flex-1 text-xs">
          {activeTab === 'settings' && (
            <form onSubmit={handleTestAndSave} className="space-y-4">
              <div className="p-4 rounded-xl bg-blue-50/40 border border-blue-100 space-y-1">
                <p className="font-semibold text-blue-950">How to get your credentials:</p>
                <p className="text-[11px] text-slate-600">
                  Open your <a href="https://supabase.com/dashboard" target="_blank" rel="noreferrer" className="text-blue-600 underline font-medium inline-flex items-center gap-0.5">Supabase Dashboard <ExternalLink className="w-2.5 h-2.5" /></a> &rarr; Select your Project &rarr; <strong>Settings</strong> &rarr; <strong>API</strong> &rarr; Copy Project URL &amp; anon public API key.
                </p>
              </div>

              <div>
                <label className="label flex items-center gap-1.5">
                  <Globe className="w-3.5 h-3.5 text-blue-600" />
                  Supabase Project URL <span className="text-rose-500">*</span>
                </label>
                <input
                  type="url"
                  value={url}
                  onChange={(e) => setUrl(e.target.value)}
                  placeholder="https://your-project-id.supabase.co"
                  className="input-field text-xs font-mono"
                  required
                />
              </div>

              <div>
                <label className="label flex items-center gap-1.5">
                  <Key className="w-3.5 h-3.5 text-blue-600" />
                  Supabase Anon / Public Key <span className="text-rose-500">*</span>
                </label>
                <input
                  type="password"
                  value={anonKey}
                  onChange={(e) => setAnonKey(e.target.value)}
                  placeholder="eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9..."
                  className="input-field text-xs font-mono"
                  required
                />
              </div>

              {testResult && (
                <div
                  className={`p-3.5 rounded-xl border text-xs flex items-start gap-2.5 ${
                    testResult.success
                      ? testResult.warning
                        ? 'bg-amber-50 border-amber-200 text-amber-900'
                        : 'bg-emerald-50 border-emerald-200 text-emerald-900'
                      : 'bg-rose-50 border-rose-200 text-rose-900'
                  }`}
                >
                  {testResult.success ? (
                    <CheckCircle2 className="w-4 h-4 text-emerald-600 shrink-0 mt-0.5" />
                  ) : (
                    <XCircle className="w-4 h-4 text-rose-600 shrink-0 mt-0.5" />
                  )}
                  <div>
                    <p className="font-semibold">{testResult.message || testResult.warning || testResult.error}</p>
                    {testResult.timestamp && (
                      <span className="text-[10px] opacity-75">Verified at {testResult.timestamp}</span>
                    )}
                  </div>
                </div>
              )}

              <div className="flex items-center justify-between pt-2 border-t border-blue-50">
                {isConfigured ? (
                  <button
                    type="button"
                    onClick={handleDisconnect}
                    className="text-xs text-rose-600 hover:text-rose-800 font-medium"
                  >
                    Disconnect Supabase
                  </button>
                ) : <div />}

                <div className="flex items-center gap-2">
                  <button
                    type="button"
                    onClick={onClose}
                    className="btn-secondary py-2 text-xs"
                  >
                    Cancel
                  </button>
                  <button
                    type="submit"
                    disabled={testing}
                    className="btn-primary py-2 text-xs bg-emerald-600 hover:bg-emerald-700"
                  >
                    {testing ? (
                      <>
                        <RefreshCw className="w-3.5 h-3.5 animate-spin" />
                        Connecting...
                      </>
                    ) : (
                      <>
                        <CheckCircle2 className="w-3.5 h-3.5" />
                        Save &amp; Connect
                      </>
                    )}
                  </button>
                </div>
              </div>
            </form>
          )}

          {activeTab === 'sql' && (
            <div className="space-y-3">
              <div className="flex items-center justify-between">
                <p className="text-slate-600 text-[11px]">
                  Copy and run this in your Supabase <strong>SQL Editor</strong> to create all tables (Users, Requests, Items, Transport, Audit, Drafts).
                </p>
                <button
                  type="button"
                  onClick={handleCopySQL}
                  className="btn-secondary py-1.5 px-3 text-xs shrink-0"
                >
                  {copied ? (
                    <>
                      <Check className="w-3.5 h-3.5 text-emerald-600" />
                      Copied!
                    </>
                  ) : (
                    <>
                      <Copy className="w-3.5 h-3.5 text-blue-600" />
                      Copy SQL Script
                    </>
                  )}
                </button>
              </div>

              <div className="bg-slate-900 text-slate-100 p-3.5 rounded-xl text-[11px] font-mono max-h-60 overflow-y-auto leading-relaxed border border-slate-800">
                <pre>{`-- Run in Supabase SQL Editor
CREATE TABLE IF NOT EXISTS public.users (...);
CREATE TABLE IF NOT EXISTS public.movement_requests (...);
CREATE TABLE IF NOT EXISTS public.movement_items (...);
CREATE TABLE IF NOT EXISTS public.transport_tasks (...);
CREATE TABLE IF NOT EXISTS public.audit_log (...);
CREATE TABLE IF NOT EXISTS public.drafts (...);
-- Click 'Copy SQL Script' above to copy full schema`}</pre>
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  )
}

