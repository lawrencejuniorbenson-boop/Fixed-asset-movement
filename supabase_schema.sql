-- 5a. New movement request: the database decides owner, status and reference.
CREATE OR REPLACE FUNCTION private.movement_request_before_insert()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
BEGIN
  IF private.is_api_user() THEN
    NEW.requesting_officer_id := private.app_user_id();
    IF NEW.requesting_officer_id IS NULL THEN
      RAISE EXCEPTION 'Your account has no staff profile.' USING ERRCODE = '42501';
    END IF;
    NEW.status := 'pending_head';
    NEW.created_at := now();
    NEW.head_approved_by := NULL;  NEW.head_approved_name := NULL;  NEW.head_approved_at := NULL;
    NEW.head_remarks := NULL;      NEW.head_signature := NULL;
    NEW.ama_officer_approved_by := NULL; NEW.ama_officer_name := NULL; NEW.ama_officer_signature := NULL;
    NEW.ama_officer_approved_at := NULL; NEW.ama_officer_remarks := NULL;
    NEW.ama_head_approved_by := NULL; NEW.ama_head_name := NULL; NEW.ama_head_signature := NULL;
    NEW.ama_head_approved_at := NULL; NEW.ama_head_remarks := NULL;
    NEW.ama_closed_by := NULL; NEW.ama_closed_name := NULL; NEW.ama_closed_at := NULL; NEW.ama_closing_remarks := NULL;
    NEW.rejection_remarks := NULL; NEW.rejected_by := NULL; NEW.rejected_at := NULL;
  END IF;

  IF NEW.fulfillment_type IS DISTINCT FROM 'it' THEN
    NEW.fulfillment_type := 'transport';
  END IF;

  NEW.reference_no := 'FAM-' || to_char(now(), 'YYYY') || '-' ||
                      lpad(nextval('public.movement_request_ref_seq')::text, 4, '0');
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS movement_request_before_insert ON public.movement_requests;
CREATE TRIGGER movement_request_before_insert
  BEFORE INSERT ON public.movement_requests
  FOR EACH ROW EXECUTE FUNCTION private.movement_request_before_insert();

-- 5b. Status changes: only the right role, only the next stage, only the
--     columns that belong to that stage. Approver identity is stamped by the
--     database, not taken from the browser.
CREATE OR REPLACE FUNCTION private.movement_request_before_update()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = ''
AS $$
DECLARE
  v_role    TEXT := private.app_role();
  v_uid     BIGINT := private.app_user_id();
  v_name    TEXT := private.app_user_name();
  v_admin   BOOLEAN := (v_role = 'admin');
  v_ama     BOOLEAN := v_role IN ('ama_officer', 'ama_head');
  v_pool    BOOLEAN;
  v_changed TEXT[];
  v_allowed TEXT[];
BEGIN
  IF NOT private.is_api_user() THEN
    RETURN NEW;  -- SQL editor / service role
  END IF;
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Your account has no staff profile.' USING ERRCODE = '42501';
  END IF;

  SELECT COALESCE(array_agg(n.key), '{}') INTO v_changed
    FROM jsonb_each(to_jsonb(NEW)) n
   WHERE n.value IS DISTINCT FROM (to_jsonb(OLD) -> n.key);

  IF cardinality(v_changed) = 0 THEN
    RETURN NEW;
  END IF;

  v_pool := (OLD.fulfillment_type = 'it'  AND v_role IN ('it_head', 'it_officer'))
         OR (OLD.fulfillment_type <> 'it' AND v_role IN ('transport_head', 'transport_officer'));

  -- Stage 1: department head approval
  IF OLD.status = 'pending_head' AND NEW.status = 'head_approved' THEN
    IF NOT (v_admin OR v_role = 'department_head') THEN
      RAISE EXCEPTION 'Only a Department Head can approve this stage.' USING ERRCODE = '42501';
    END IF;
    v_allowed := ARRAY['status','head_approved_by','head_approved_name','head_approved_at','head_remarks','head_signature'];
    NEW.head_approved_by := v_uid; NEW.head_approved_name := v_name;
    NEW.head_signature := v_name;  NEW.head_approved_at := now();

  -- Stage 2: AMA verification
  ELSIF OLD.status = 'head_approved' AND NEW.status = 'ama_officer_approved' THEN
    IF NOT (v_admin OR v_ama) THEN
      RAISE EXCEPTION 'Only the Asset Management & Archives pool can verify this stage.' USING ERRCODE = '42501';
    END IF;
    v_allowed := ARRAY['status','ama_officer_approved_by','ama_officer_name','ama_officer_signature','ama_officer_approved_at','ama_officer_remarks'];
    NEW.ama_officer_approved_by := v_uid; NEW.ama_officer_name := v_name;
    NEW.ama_officer_signature := v_name;  NEW.ama_officer_approved_at := now();

  -- Stage 3: AMA final authorization
  ELSIF OLD.status = 'ama_officer_approved' AND NEW.status = 'fully_approved' THEN
    IF NOT (v_admin OR v_ama) THEN
      RAISE EXCEPTION 'Only the Asset Management & Archives pool can authorize this stage.' USING ERRCODE = '42501';
    END IF;
    v_allowed := ARRAY['status','ama_head_approved_by','ama_head_name','ama_head_signature','ama_head_approved_at','ama_head_remarks'];
    NEW.ama_head_approved_by := v_uid; NEW.ama_head_name := v_name;
    NEW.ama_head_signature := v_name;  NEW.ama_head_approved_at := now();

  -- Stage 4: physical movement by the Transport or IT pool
  ELSIF (OLD.status = 'fully_approved' AND NEW.status = 'in_transport')
     OR (OLD.status = 'in_transport'   AND NEW.status = 'transport_completed') THEN
    IF NOT (v_admin OR v_pool) THEN
      RAISE EXCEPTION 'Only the assigned Transport / IT pool can update the movement.' USING ERRCODE = '42501';
    END IF;
    v_allowed := ARRAY['status'];

  -- Stage 5: AMA closes the file
  ELSIF OLD.status = 'transport_completed' AND NEW.status = 'closed' THEN
    IF NOT (v_admin OR v_ama) THEN
      RAISE EXCEPTION 'Only the Asset Management & Archives pool can close a request.' USING ERRCODE = '42501';
    END IF;
    v_allowed := ARRAY['status','ama_closed_by','ama_closed_name','ama_closed_at','ama_closing_remarks'];
    NEW.ama_closed_by := v_uid; NEW.ama_closed_name := v_name; NEW.ama_closed_at := now();

  -- Rejection by whoever owns the current approval stage
  ELSIF NEW.status = 'rejected' AND OLD.status IN ('pending_head', 'head_approved', 'ama_officer_approved') THEN
    IF NOT (v_admin
            OR (OLD.status = 'pending_head' AND v_role = 'department_head')
            OR (OLD.status IN ('head_approved', 'ama_officer_approved') AND v_ama)) THEN
      RAISE EXCEPTION 'You cannot reject a request at this stage.' USING ERRCODE = '42501';
    END IF;
    v_allowed := ARRAY['status','rejection_remarks','rejected_by','rejected_at'];
    NEW.rejected_by := v_uid; NEW.rejected_at := now();

  ELSE
    IF v_admin THEN
      RETURN NEW;  -- administrators may correct records
    END IF;
    RAISE EXCEPTION 'Invalid status change: % -> %', OLD.status, NEW.status USING ERRCODE = '42501';
  END IF;

  -- Separation of duties: nobody approves their own request.
  IF NOT v_admin AND NEW.status <> 'rejected' AND OLD.requesting_officer_id = v_uid
     AND OLD.status IN ('pending_head', 'head_approved', 'ama_officer_approved', 'transport_completed') THEN
    RAISE EXCEPTION 'You cannot approve or close your own request.' USING ERRCODE = '42501';
  END IF;

  IF NOT v_admin AND NOT (v_changed <@ v_allowed) THEN
    RAISE EXCEPTION 'This action may not change: %',
      array_to_string(ARRAY(SELECT unnest(v_changed) EXCEPT SELECT unnest(v_allowed)), ', ')
      USING ERRCODE = '42501';
  END IF;

  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS movement_request_before_update ON public.movement_requests;
CREATE TRIGGER movement_request_before_update
  BEFORE UPDATE ON public.movement_requests
  FOR EACH ROW EXECUTE FUNCTION private.movement_request_before_update();

-- 5c. Final authorization automatically opens the Transport / IT task.
CREATE OR REPLACE FUNCTION private.movement_request_after_update()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
BEGIN
  IF NEW.status = 'fully_approved' AND OLD.status IS DISTINCT FROM 'fully_approved'
     AND NOT EXISTS (SELECT 1 FROM public.transport_tasks WHERE movement_request_id = NEW.id) THEN
    INSERT INTO public.transport_tasks (movement_request_id, fulfillment_type, scheduled_date, status)
    VALUES (NEW.id, NEW.fulfillment_type, NEW.movement_date, 'pending_assignment');
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS movement_request_after_update ON public.movement_requests;
CREATE TRIGGER movement_request_after_update
  AFTER UPDATE OF status ON public.movement_requests
  FOR EACH ROW EXECUTE FUNCTION private.movement_request_after_update();

-- 5d. Transport / IT tasks: fixed links, forward-only status, stamped officers.
CREATE OR REPLACE FUNCTION private.transport_task_before_update()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = ''
AS $$
DECLARE
  v_admin BOOLEAN := private.app_role() = 'admin';
BEGIN
  IF NOT private.is_api_user() OR v_admin THEN
    RETURN NEW;
  END IF;
  IF NEW.movement_request_id IS DISTINCT FROM OLD.movement_request_id
     OR NEW.fulfillment_type IS DISTINCT FROM OLD.fulfillment_type
     OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
    RAISE EXCEPTION 'Task links cannot be changed.' USING ERRCODE = '42501';
  END IF;
  IF NEW.status IS DISTINCT FROM OLD.status AND NOT (
       (OLD.status IN ('pending_assignment', 'officer_assigned') AND NEW.status = 'officer_assigned')
    OR (OLD.status = 'officer_assigned' AND NEW.status = 'in_progress')
    OR (OLD.status = 'in_progress'      AND NEW.status = 'completed')) THEN
    RAISE EXCEPTION 'Invalid task status change: % -> %', OLD.status, NEW.status USING ERRCODE = '42501';
  END IF;
  IF OLD.status = 'completed' THEN
    RAISE EXCEPTION 'Completed tasks cannot be edited.' USING ERRCODE = '42501';
  END IF;
  IF NEW.status = 'in_progress' AND OLD.status <> 'in_progress' THEN
    NEW.transport_started_by := private.app_user_id();
    NEW.transport_started_name := private.app_user_name();
  ELSIF NEW.status = 'completed' AND OLD.status <> 'completed' THEN
    NEW.transport_completed_by := private.app_user_id();
    NEW.transport_completed_name := private.app_user_name();
    NEW.completed_at := now();
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS transport_task_before_update ON public.transport_tasks;
CREATE TRIGGER transport_task_before_update
  BEFORE UPDATE ON public.transport_tasks
  FOR EACH ROW EXECUTE FUNCTION private.transport_task_before_update();

-- 5e. Audit entries are attributed to the real signed-in user.
CREATE OR REPLACE FUNCTION private.audit_log_before_insert()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = ''
AS $$
DECLARE
  v_name TEXT := private.app_user_name();
BEGIN
  IF private.is_api_user() THEN
    NEW.performed_by := private.app_user_id();
    NEW.created_at := now();
    IF NEW.performed_by_name IS NULL OR position(v_name IN NEW.performed_by_name) <> 1 THEN
      NEW.performed_by_name := v_name;
    END IF;
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS audit_log_before_insert ON public.audit_log;
CREATE TRIGGER audit_log_before_insert
  BEFORE INSERT ON public.audit_log
  FOR EACH ROW EXECUTE FUNCTION private.audit_log_before_insert();

-- 5f. Profiles: only lower-cased emails; auth links cannot be forged via the API.
CREATE OR REPLACE FUNCTION private.users_before_write()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = ''
AS $$
BEGIN
  NEW.email := lower(trim(NEW.email));
  IF private.is_api_user() THEN
    IF TG_OP = 'INSERT' THEN
      NEW.auth_id := NULL;  -- linked only by the sign-up trigger
    ELSIF NEW.auth_id IS DISTINCT FROM OLD.auth_id AND NEW.auth_id IS NOT NULL THEN
      RAISE EXCEPTION 'auth_id can only be cleared, not set.' USING ERRCODE = '42501';
    ELSIF NEW.email IS DISTINCT FROM OLD.email AND OLD.auth_id IS NOT NULL THEN
      RAISE EXCEPTION 'Email of an activated account cannot be changed here.' USING ERRCODE = '42501';
    END IF;
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS users_before_write ON public.users;
CREATE TRIGGER users_before_write
  BEFORE INSERT OR UPDATE ON public.users
  FOR EACH ROW EXECUTE FUNCTION private.users_before_write();

