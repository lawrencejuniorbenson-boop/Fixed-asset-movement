-- 1. Users Table
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT UNIQUE NOT NULL,
  password TEXT,
  role TEXT NOT NULL DEFAULT 'requesting_officer',
  department TEXT,
  staff_id TEXT,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Movement Requests Table
CREATE TABLE IF NOT EXISTS public.movement_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference_no TEXT UNIQUE NOT NULL,
  requesting_officer_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  requesting_officer_staff_id TEXT,
  present_location TEXT NOT NULL,
  new_location TEXT NOT NULL,
  purpose TEXT NOT NULL,
  fulfillment_type TEXT NOT NULL DEFAULT 'transport',
  officer_doing_movement TEXT,
  officer_doing_movement_staff_id TEXT,
  authorized_by TEXT,
  authorized_by_staff_id TEXT,
  department TEXT,
  unit TEXT,
  movement_date DATE NOT NULL DEFAULT CURRENT_DATE,
  priority TEXT NOT NULL DEFAULT 'Normal',
  signature_requester TEXT,
  status TEXT NOT NULL DEFAULT 'pending_head',
  
  -- Stage 1: Department / Unit Head Approval
  head_approved_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  head_approved_at TIMESTAMPTZ,
  head_remarks TEXT,
  head_signature TEXT,
  
  -- Stage 2: AMA Officer Verification
  ama_officer_approved_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  ama_officer_approved_at TIMESTAMPTZ,
  ama_officer_remarks TEXT,
  
  -- Stage 3: Head of Fixed Assets Final Authorization
  ama_head_approved_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  ama_head_name TEXT,
  ama_head_signature TEXT,
  ama_head_approved_at TIMESTAMPTZ,
  ama_head_remarks TEXT,
  
  -- Stage 5: Register Updated & Formally Closed by AMA
  ama_closed_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  ama_closed_name TEXT,
  ama_closed_at TIMESTAMPTZ,
  ama_closing_remarks TEXT,
  
  -- Rejection details
  rejection_remarks TEXT,
  
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Movement Asset Items Schedule Table
CREATE TABLE IF NOT EXISTS public.movement_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  movement_request_id BIGINT REFERENCES public.movement_requests(id) ON DELETE CASCADE NOT NULL,
  item_no INT NOT NULL DEFAULT 1,
  name_of_asset TEXT NOT NULL,
  asset_code TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Logistics & Fulfillment Tasks Table (Transport / IT)
CREATE TABLE IF NOT EXISTS public.transport_tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  movement_request_id BIGINT REFERENCES public.movement_requests(id) ON DELETE CASCADE NOT NULL,
  fulfillment_type TEXT NOT NULL DEFAULT 'transport',
  assigned_officer_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  assigned_officer_name TEXT,
  vehicle_details TEXT,
  driver_type TEXT DEFAULT 'internal',
  driver_name TEXT,
  vendor_name TEXT,
  scheduled_date DATE,
  assessment_notes TEXT,
  assignment_notes TEXT,
  status TEXT NOT NULL DEFAULT 'pending_assignment',
  completed_at TIMESTAMPTZ,
  completion_notes TEXT,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

