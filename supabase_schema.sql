-- =============================================================================
-- Fixed Asset Movement Service - Supabase Database Schema
-- Run this whole script in your Supabase SQL Editor
-- (https://supabase.com/dashboard/project/_/sql).
--
-- It is idempotent: safe on a fresh project AND safe to re-run on an existing
-- deployment (it upgrades the old permissive setup in place and keeps data).
--
-- SECURITY MODEL
--   * Sign-in is handled by Supabase Auth (auth.users). Passwords are never
--     stored in public tables.
--   * public.users holds the staff profile + ROLE. Each profile is linked to
--     one auth user via users.auth_id. Only admins can change roles.
--   * Every table has Row Level Security. The anon role has no access at all.
--   * Workflow rules (who may approve which stage) are enforced by database
--     triggers, so a user cannot bypass them by calling the API directly.
--
-- REQUIRED SUPABASE AUTH SETTINGS (Dashboard -> Authentication -> Providers -> Email)
--   * "Confirm email" MUST stay ON. Existing staff profiles are linked to a
--     sign-up by email address only after that email is confirmed.
-- =============================================================================


-- =============================================================================
-- 1. TABLES
