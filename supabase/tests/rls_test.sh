#!/bin/bash
# Security regression tests for supabase_schema.sql, run against a plain local
# PostgreSQL with Supabase's auth schema stubbed (supabase_stub.sql).
#
# Usage:  PGHOST=127.0.0.1 PGPORT=5432 PGUSER=postgres ./supabase/tests/rls_test.sh
# It (re)creates a scratch database named fam_rls_test.
set -u
cd "$(dirname "$0")"
DB=fam_rls_test
psql -q -v ON_ERROR_STOP=1 -c "drop database if exists $DB" -c "create database $DB" >/dev/null || exit 1
psql -q -v ON_ERROR_STOP=1 -d $DB -f supabase_stub.sql >/dev/null || exit 1
psql -q -v ON_ERROR_STOP=1 -d $DB -c "create table public.users (id bigint generated by default as identity primary key, name text not null, email text unique not null, password text, role text not null default 'requesting_officer', department text, staff_id text, created_at timestamptz default now())" \
  -c "insert into public.users (name,email,password,role,department) values ('Ada Admin','Admin@Bank.com','Admin@123','admin','IT'),('Rita Requester','rita@bank.com','pw','requesting_officer','Ops'),('Dan Head','dan@bank.com','pw','department_head','Ops'),('Amy Ama','amy@bank.com','pw','ama_officer','Assets'),('Tom Transport','tom@bank.com','pw','transport_officer','Transport'),('Ivy IT','ivy@bank.com','pw','it_officer','IT'),('Aud Auditor','aud@bank.com','pw','auditor','Audit')" >/dev/null || exit 1
# Apply the schema twice: proves it upgrades a legacy table and is re-runnable.
for i in 1 2; do psql -q -v ON_ERROR_STOP=1 -d $DB -f ../../supabase_schema.sql >/dev/null 2>&1 || { echo "schema failed to apply"; exit 1; }; done
psql -q -v ON_ERROR_STOP=1 -d $DB -c "insert into public.movement_requests (present_location,new_location,purpose,requesting_officer_id) values ('A','B','old',2)" >/dev/null || exit 1
P="psql -d $DB -q -At"
PASS=0; FAIL=0
uid() { $P -c "select id from auth.users where email='$1'"; }
run_as() { # email sql -> prints output / error
  local sub; sub=$(uid "$1")
  $P -v ON_ERROR_STOP=1 2>&1 <<SQL
begin;
set local role authenticated;
select set_config('request.jwt.claims', '{"sub":"$sub","role":"authenticated"}', true) \gset
$2
commit;
SQL
}
run_anon() { $P -v ON_ERROR_STOP=1 2>&1 <<SQL
begin; set local role anon; select set_config('request.jwt.claims','{"role":"anon"}',true) \gset
$1
commit;
SQL
}
expect_ok()   { local out; out=$("$@"); if echo "$out" | grep -q "ERROR"; then echo "FAIL (expected ok): ${*:2}"; echo "   $out"; FAIL=$((FAIL+1)); else PASS=$((PASS+1)); fi; }
expect_err()  { local pat=$1; shift; local out; out=$("$@"); if echo "$out" | grep -qi "$pat"; then PASS=$((PASS+1)); else echo "FAIL (expected error '$pat'): ${*:2}"; echo "   got: $out"; FAIL=$((FAIL+1)); fi; }
expect_eq()   { local want=$1; shift; local out; out=$("$@" | tail -1); if [ "$out" == "$want" ]; then PASS=$((PASS+1)); else echo "FAIL (expected '$want'): ${*:2}"; echo "   got: $out"; FAIL=$((FAIL+1)); fi; }

# --- Sign-ups (simulating Supabase Auth) ---
$P -c "insert into auth.users(email,email_confirmed_at,raw_user_meta_data) values
 ('admin@bank.com',now(),'{}'),('rita@bank.com',now(),'{}'),('dan@bank.com',now(),'{}'),
 ('amy@bank.com',now(),'{}'),('tom@bank.com',now(),'{}'),('ivy@bank.com',now(),'{}'),('aud@bank.com',now(),'{}')"
# Attacker: new sign-up claiming admin role in metadata
$P -c "insert into auth.users(email,email_confirmed_at,raw_user_meta_data) values ('eve@evil.com',now(),'{\"name\":\"Eve\",\"role\":\"admin\"}')"
# Attacker: unconfirmed sign-up using a pre-registered email
$P -c "insert into public.users(name,email,role) values ('Pre Head','prehead@bank.com','department_head')"
$P -c "insert into auth.users(email,email_confirmed_at) values ('prehead@bank.com',null)"

echo "== Profile linking"
expect_eq "admin" $P -c "select role from public.users where email='admin@bank.com' and auth_id is not null"
expect_eq "requesting_officer" $P -c "select role from public.users where email='eve@evil.com'"
expect_eq "t" $P -c "select auth_id is null from public.users where email='prehead@bank.com'"
$P -c "update auth.users set email_confirmed_at=now() where email='prehead@bank.com'"
expect_eq "department_head" $P -c "select role from public.users where email='prehead@bank.com' and auth_id is not null"

echo "== Anonymous access"
expect_err "permission denied" run_anon "select count(*) from public.users;"
expect_err "permission denied" run_anon "select count(*) from public.movement_requests;"

echo "== Privilege escalation"
expect_eq "0" run_as eve@evil.com "with u as (update public.users set role='admin' where email='eve@evil.com' returning 1) select count(*) from u;"
expect_err "row-level security" run_as eve@evil.com "insert into public.users(name,email,role) values ('x','x@x.com','admin');"
expect_eq "0" run_as eve@evil.com "with d as (delete from public.users returning 1) select count(*) from d;"
expect_err "does not exist\|permission denied" run_as eve@evil.com "select password from public.users;"

echo "== Request visibility"
expect_eq "0" run_as eve@evil.com "select count(*) from public.movement_requests;"
expect_eq "1" run_as rita@bank.com "select count(*) from public.movement_requests;"
expect_eq "0" run_as tom@bank.com "select count(*) from public.movement_requests;"

echo "== Create request (forged fields ignored)"
expect_ok run_as rita@bank.com "insert into public.movement_requests(reference_no,requesting_officer_id,present_location,new_location,purpose,status,head_approved_by) values ('HACK',1,'X','Y','new','closed',1);"
expect_eq "2|pending_head||t" $P -c "select requesting_officer_id,status,head_approved_by,reference_no like 'FAM-____-0002' from public.movement_requests where purpose='new'"
RID=$($P -c "select id from public.movement_requests where purpose='new'")
expect_ok run_as rita@bank.com "insert into public.movement_items(movement_request_id,name_of_asset,asset_code) values ($RID,'Desk','A1');"
expect_err "row-level security" run_as eve@evil.com "insert into public.movement_items(movement_request_id,name_of_asset,asset_code) values ($RID,'Bomb','Z');"
expect_ok run_as rita@bank.com "insert into public.audit_log(movement_request_id,action,performed_by,performed_by_name) values ($RID,'REQUEST_SUBMITTED',1,'Ada Admin');"
expect_eq "2|Rita Requester" $P -c "select performed_by,performed_by_name from public.audit_log where movement_request_id=$RID"
expect_eq "0" run_as rita@bank.com "with d as (delete from public.audit_log returning 1) select count(*) from d;"

echo "== Workflow: wrong roles blocked"
expect_eq "0" run_as rita@bank.com "with u as (update public.movement_requests set status='head_approved' where id=$RID returning 1) select count(*) from u;"
expect_err "Invalid status change" run_as amy@bank.com "update public.movement_requests set status='ama_officer_approved' where id=$RID;"
expect_err "Invalid status change" run_as dan@bank.com "update public.movement_requests set status='closed' where id=$RID;"
expect_err "may not change" run_as dan@bank.com "update public.movement_requests set status='head_approved', new_location='My house' where id=$RID;"

echo "== Workflow: happy path"
expect_ok run_as dan@bank.com "update public.movement_requests set status='head_approved', head_approved_by=1, head_approved_name='Fake', head_remarks='ok' where id=$RID;"
expect_eq "3|Dan Head" $P -c "select head_approved_by, head_approved_name from public.movement_requests where id=$RID"
expect_err "Only the Asset Management" run_as dan@bank.com "update public.movement_requests set status='fully_approved' where id=$RID;"
# One AMA approval verifies and authorizes in a single step
expect_ok run_as amy@bank.com "update public.movement_requests set status='fully_approved', ama_officer_remarks='verified' where id=$RID;"
expect_eq "4|Amy Ama|4|Amy Ama|verified" $P -c "select ama_officer_approved_by, ama_officer_name, ama_head_approved_by, ama_head_name, ama_head_remarks from public.movement_requests where id=$RID"
expect_eq "transport|pending_assignment" $P -c "select fulfillment_type,status from public.transport_tasks where movement_request_id=$RID"
TID=$($P -c "select id from public.transport_tasks where movement_request_id=$RID")
expect_eq "1" run_as tom@bank.com "select count(*) from public.movement_requests;"
expect_eq "0" run_as ivy@bank.com "with u as (update public.transport_tasks set status='officer_assigned' where id=$TID returning 1) select count(*) from u;"
expect_err "Invalid task status" run_as tom@bank.com "update public.transport_tasks set status='completed' where id=$TID;"
expect_ok run_as tom@bank.com "update public.transport_tasks set status='officer_assigned', assigned_officer_name='Tom', vehicle_details='Van' where id=$TID;"
expect_ok run_as tom@bank.com "update public.transport_tasks set status='in_progress' where id=$TID; update public.movement_requests set status='in_transport' where id=$RID;"
expect_ok run_as tom@bank.com "update public.transport_tasks set status='completed', completion_notes='done' where id=$TID; update public.movement_requests set status='transport_completed' where id=$RID;"
expect_eq "5|Tom Transport" $P -c "select transport_completed_by, transport_completed_name from public.transport_tasks where id=$TID"
expect_err "Only the Asset Management" run_as tom@bank.com "update public.movement_requests set status='closed' where id=$RID;"
expect_ok run_as amy@bank.com "update public.movement_requests set status='closed', ama_closing_remarks='reg updated' where id=$RID;"
expect_eq "closed|4" $P -c "select status, ama_closed_by from public.movement_requests where id=$RID"

echo "== Separation of duties & rejection"
expect_ok run_as dan@bank.com "insert into public.movement_requests(reference_no,present_location,new_location,purpose) values ('x','A','B','dan-own');"
DID=$($P -c "select id from public.movement_requests where purpose='dan-own'")
expect_err "your own request" run_as dan@bank.com "update public.movement_requests set status='head_approved' where id=$DID;"
expect_ok run_as prehead@bank.com "update public.movement_requests set status='rejected', rejection_remarks='no' where id=$DID;"
expect_eq "1" run_as prehead@bank.com "select count(*) from public.movement_requests where id=$DID;"

echo "== IT pool isolation"
expect_ok run_as rita@bank.com "insert into public.movement_requests(reference_no,present_location,new_location,purpose,fulfillment_type) values ('x','DC1','DC2','it-move','it');"
IID=$($P -c "select id from public.movement_requests where purpose='it-move'")
expect_ok run_as dan@bank.com "update public.movement_requests set status='head_approved' where id=$IID;"
# Legacy two-step AMA path still works for requests created by older versions
expect_ok run_as amy@bank.com "update public.movement_requests set status='ama_officer_approved' where id=$IID;"
expect_ok run_as amy@bank.com "update public.movement_requests set status='fully_approved' where id=$IID;"
expect_eq "0" run_as tom@bank.com "select count(*) from public.transport_tasks where movement_request_id=$IID;"
expect_eq "1" run_as ivy@bank.com "select count(*) from public.transport_tasks where movement_request_id=$IID;"
expect_eq "0" run_as tom@bank.com "with u as (update public.movement_requests set status='in_transport' where id=$IID returning 1) select count(*) from u;"
expect_err "Only the assigned" run_as amy@bank.com "update public.movement_requests set status='in_transport' where id=$IID;"

echo "== Drafts"
expect_ok run_as rita@bank.com "insert into public.drafts(user_id,form) values ('2','{\"a\":1}');"
expect_err "row-level security" run_as eve@evil.com "insert into public.drafts(user_id,form) values ('2','{}');"
expect_eq "0" run_as eve@evil.com "select count(*) from public.drafts;"

echo "== Admin"
expect_ok run_as admin@bank.com "insert into public.users(name,email,role) values ('New Hire','New.Hire@Bank.com','ama_head');"
expect_eq "ama_head|" $P -c "select role, auth_id from public.users where email='new.hire@bank.com'"
expect_ok run_as admin@bank.com "update public.users set role='department_head' where email='eve@evil.com';"
expect_eq "4" run_as aud@bank.com "select count(*) from public.movement_requests;"
expect_eq "0" run_as aud@bank.com "with u as (update public.movement_requests set status='closed' returning 1) select count(*) from u;"

echo "== Access mode: login (default)"
$P -c "insert into auth.users(id,email) values ('00000000-0000-0000-0000-00000000a001',null)"
ANON_SUB=00000000-0000-0000-0000-00000000a001
run_anon_session() { $P -v ON_ERROR_STOP=1 2>&1 <<SQL
begin; set local role authenticated;
select set_config('request.jwt.claims', '{"sub":"$ANON_SUB","role":"authenticated","is_anonymous":true}', true) \\gset
$1
commit;
SQL
}
expect_eq "login" run_anon "select public.app_mode();"
expect_eq "0" run_anon_session "select count(*) from public.open_access_staff();"
expect_err "Open access is disabled" run_anon_session "select public.open_access_act_as(1);"
expect_eq "0" run_anon_session "select count(*) from public.movement_requests;"
expect_err "permission denied" run_anon "select public.open_access_staff();"

echo "== Access mode: open"
$P -c "update private.settings set value='open' where key='access_mode'"
expect_eq "open" run_anon "select public.app_mode();"
expect_eq "t" run_anon_session "select count(*) > 5 from public.open_access_staff();"
expect_ok run_anon_session "select public.open_access_act_as(2);"
expect_eq "Rita Requester|requesting_officer" run_anon_session "select name, role from public.my_profile();"
expect_ok run_anon_session "insert into public.movement_requests(reference_no,present_location,new_location,purpose) values ('x','A','B','open-mode');"
expect_eq "2" $P -c "select requesting_officer_id from public.movement_requests where purpose='open-mode'"
OID=$($P -c "select id from public.movement_requests where purpose='open-mode'")
expect_eq "0" run_anon_session "with u as (update public.movement_requests set status='head_approved' where id=$OID returning 1) select count(*) from u;"
expect_ok run_anon_session "select public.open_access_act_as(3);"
expect_ok run_anon_session "update public.movement_requests set status='head_approved' where id=$OID;"
expect_eq "Dan Head" $P -c "select head_approved_name from public.movement_requests where id=$OID"
expect_err "permission denied" run_anon "select count(*) from public.movement_requests;"
expect_err "already exist" run_anon_session "select public.open_access_bootstrap_admin('X','x@x.com');"
expect_err "Unknown staff" run_anon_session "select public.open_access_act_as(999999);"
# A real signed-in account is unaffected by open mode
expect_eq "Rita Requester" run_as rita@bank.com "select name from public.my_profile();"

echo "== Back to login mode"
$P -c "update private.settings set value='login' where key='access_mode'"
expect_eq "0" run_anon_session "select count(*) from public.movement_requests;"
expect_eq "0" run_anon_session "select count(*) from public.my_profile();"
expect_eq "Dan Head" run_as dan@bank.com "select name from public.my_profile();"
expect_eq "login" $P -c "select value from private.settings where key='access_mode'"

echo
echo "PASSED: $PASS   FAILED: $FAIL"
[ "$FAIL" -eq 0 ]
